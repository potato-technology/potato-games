function tl(k, vars) {
  const lang = (window.Potato && Potato.lang) || 'en';
  const L = I18N[lang] || I18N.en;
  let s = L[k] != null ? L[k] : I18N.en[k] != null ? I18N.en[k] : k;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, v) => (vars[v] != null ? vars[v] : m));
  return s;
}

// Font fallbacks for Korean, Japanese and Chinese letters, with the player's own language first
// (so Japanese kana don't borrow the Korean font's shapes).
function cjkFont() {
  const lang = (window.Potato && Potato.lang) || 'en';
  const base = window.Potato ? Potato.font : 'sans-serif';
  if (lang === 'ja') return "'Hiragino Sans', 'Yu Gothic', 'Meiryo', " + base;
  if (lang === 'zh') return "'PingFang SC', 'Microsoft YaHei', " + base;
  return base;
}

// Fills every element marked data-i18n="key" (the HTML may hold <kbd>, <b> or <small>).
function applyI18n() {
  document.documentElement.lang = (window.Potato && Potato.lang) || 'en';
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = tl(el.dataset.i18n); });
}
